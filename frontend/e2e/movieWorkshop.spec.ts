import { expect, test } from '@playwright/test'
import { SHOW_EXTRA_PAGES } from '../src/features'

// this page is hidden, not deleted (features.ts, SHOW_EXTRA_PAGES); its tests run again when it is shown
test.skip(!SHOW_EXTRA_PAGES, 'page hidden')

test('classroom journey connects prediction, 3D, an actual experiment and evidence', async ({ page, request }, testInfo) => {
  test.setTimeout(180_000)
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.goto('/activities')
  await page.getByTestId('hub-movie-workshop').click()
  await expect(page.getByRole('heading', { name: 'Can money buy a better movie rating?' })).toBeVisible()
  await expect(page.locator('.movie-card')).toHaveCount(3)
  await page.screenshot({ path: testInfo.outputPath('movies-story.png'), fullPage: true })
  await page.getByRole('button', { name: 'Make a prediction →' }).click()
  await expect(page.getByRole('button', { name: 'Inspect the fit in 3D →' })).toBeDisabled()
  await page.getByRole('button', { name: 'A small improvement', exact: true }).click()
  await page.getByRole('button', { name: 'Inspect the fit in 3D →' }).click()
  await expect(page.getByTestId('gd-explanation')).toBeVisible()
  await page.getByRole('button', { name: '2. Reveal the bowl' }).click()
  await page.keyboard.press('Space')
  await page.waitForTimeout(4200)
  await page.keyboard.press('Space')
  await page.screenshot({ path: testInfo.outputPath('movies-bowl.png'), fullPage: true })
  await page.getByRole('button', { name: 'Try the learning-rate experiment →' }).click()
  await page.getByRole('button', { name: 'It could overshoot', exact: true }).click()
  await page.getByRole('button', { name: 'Test the prediction', exact: true }).click()
  await expect(page.getByTestId('workshop-comparison')).toContainText('Cost increased')
  await expect(page.locator('.result.stable')).toContainText('α = 0.1')
  const config = (await (await request.get('http://localhost:8000/api/v1/lessons/shah-8-4-movies')).json()).parts[1].config
  const fast = (await (await request.post('http://localhost:8000/api/v1/simulations/linreg-gd', { data: { ...config, learning_rate: 2.2, iterations: 80 } })).json()).trace
  expect(fast.final.cost).toBeGreaterThan(fast.initial_cost)
  await expect(page.locator('.result.fast')).toContainText(fast.final.cost.toExponential(3))
  await page.screenshot({ path: testInfo.outputPath('movies-experiment.png'), fullPage: true })
  await page.locator('.result.fast').getByRole('button').click()
  await expect(page.getByTestId('gd-cost')).toBeVisible()
  await expect(page.getByTestId('gd-explanation')).toContainText('gradient')
  await page.getByRole('navigation', { name: 'Classroom journey' }).getByRole('button', { name: 'Solution' }).click()
  await expect(page.getByTestId('workshop-stage-4')).toContainText('A small improvement')
  const manifest = await (await request.get('http://localhost:8000/api/v1/lessons/shah-8-4-movies')).json()
  const trace = (await (await request.post('http://localhost:8000/api/v1/simulations/linreg-gd', { data: manifest.parts[1].config })).json()).trace
  await expect(page.getByTestId('workshop-solution')).toContainText(`${(trace.ols.r2 * 100).toFixed(1)}%`)
  await page.getByText('Return to one movie: inspect a prediction', { exact: true }).click()
  await expect(page.getByTestId('workshop-stage-4')).toContainText('unseen movies')
  await page.screenshot({ path: testInfo.outputPath('movies-solution.png'), fullPage: true })
  await page.getByRole('button', { name: 'Add a predictor: watch the movie plane →' }).click()
  await expect(page.getByTestId('gd-explanation')).toContainText('movie')
  expect(errors).toEqual([])
})

test('classroom stages fit a small screen and work with reduced motion and keyboard navigation', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/workshops/movies')
  await expect(page.locator('.movie-card')).toHaveCount(3)
  await page.keyboard.press('l')
  await expect(page.getByTestId('movie-workshop')).toHaveAttribute('data-theme', 'light')
  await page.screenshot({ path: testInfo.outputPath('movies-mobile-light.png'), fullPage: true })
  await page.keyboard.press('l')
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('workshop-stage-1')).toBeVisible()
  await page.getByRole('button', { name: 'I need evidence', exact: true }).click()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('play')).toBeVisible()
  await page.getByRole('navigation', { name: 'Classroom journey' }).getByRole('button', { name: 'Solution' }).click()
  await expect(page.getByTestId('workshop-solution')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
